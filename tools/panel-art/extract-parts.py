# Writes src/ui/DesignParts.h from the panel SVG: the scalloped trimmer cap and
# the cutoff knob outlines, verbatim from the Figma export.
# Usage: python3 extract-parts.py build/panel.svg ../../src/ui/DesignParts.h
import re
import sys

svg = open(sys.argv[1]).read()

def path_starting(prefix):
    return re.search(r'd="(' + re.escape(prefix) + r'[^"]+)"', svg).group(1).strip()

trimmer = path_starting('M 62.910156 304.410156')
cutoff = path_starting('M 949 179.429688')

with open(sys.argv[2], 'w') as out:
    out.write('''#pragma once

// Outlines taken verbatim from the Figma export of the Moduleur panel
// (design points; 1 pt = kPtToPanel panel units). Generated by
// tools/panel-art/extract-parts.py - do not edit by hand.
namespace moduleur::ui::design
{
// Scalloped trimmer cap (20 teeth), centred on (64, 320).
inline constexpr float kTrimmerCapCentreX = 64.0f, kTrimmerCapCentreY = 320.0f;
inline constexpr const char* kTrimmerCapPath = "%s";

// Filter cutoff knob with its pointer tab, centred on (944, 208).
inline constexpr float kCutoffCentreX = 944.0f, kCutoffCentreY = 208.0f;
inline constexpr const char* kCutoffPath = "%s";
} // namespace moduleur::ui::design
''' % (trimmer, cutoff))
